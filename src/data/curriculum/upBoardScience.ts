function makeTopic(
  subjectId: string,
  chapterId: string,
  idx: number,
  en: string,
  hi: string,
  subtopics: BilingualText[] = [],
  importance: CurriculumTopic['importance'] = 'core',
  verificationStatus: CurriculumTopic['verificationStatus'] = 'verified'
): CurriculumTopic {
  return {
    id: `${chapterId}-t${idx}`,
    chapterId,
    subjectId,
    title: { en, hi },
    subtopics,
    syllabusCode: `${subjectId.toUpperCase()}-${idx}`,
    inclusionStatus: 'included',
    importance,
    order: idx,
    isPublished: true,
    verificationStatus,
  };
}

